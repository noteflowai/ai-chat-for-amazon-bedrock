#!/usr/bin/env bash
#
# Install the code quality tools this project checks against.
#
# Pinned on purpose: an unpinned linter turns an unrelated upstream release into a
# failing build. Bump the versions below deliberately and review what changes.
#
# No Composer required, which matters because the PHP available on a small host often
# lacks the extensions Composer wants. Everything lands in .tools/, which is ignored by
# git and excluded from the distributed package.
#
# Usage:
#   bin/setup-tools.sh            # install anything missing
#   bin/setup-tools.sh --force    # reinstall from scratch
#   bin/setup-tools.sh --check    # report what is installed and exit

set -uo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS_DIR="$PROJECT_DIR/.tools"

# PHP_CodeSniffer 4 changed sniff APIs that WPCS 3 does not target yet, so stay on the
# 3.x line. 3.13.6 is the newest 3.x release; 3.13.7 exists only on the master branch.
PHPCS_VERSION='3.13.6'
WPCS_VERSION='3.4.1'
PHPCSUTILS_VERSION='1.2.3'
PHPCSEXTRA_VERSION='1.5.1'

FORCE=0
CHECK_ONLY=0
while [ $# -gt 0 ]; do
	case "$1" in
		--force) FORCE=1; shift ;;
		--check) CHECK_ONLY=1; shift ;;
		*) printf 'Unknown option: %s\n' "$1" >&2; exit 2 ;;
	esac
done

# Paths are relative to the project root on purpose: the PHP that runs phpcs may live
# in a container whose working directory is the project, where an absolute host path
# would not exist.
phpcs_entry() { printf '.tools/PHP_CodeSniffer-%s/bin/phpcs' "$PHPCS_VERSION"; }
phpcbf_entry() { printf '.tools/PHP_CodeSniffer-%s/bin/phpcbf' "$PHPCS_VERSION"; }

installed_paths() {
	printf '.tools/WordPress-Coding-Standards-%s,.tools/PHPCSUtils-%s,.tools/PHPCSExtra-%s' \
		"$WPCS_VERSION" "$PHPCSUTILS_VERSION" "$PHPCSEXTRA_VERSION"
}

report() {
	printf 'tools directory: %s\n' "$TOOLS_DIR"
	local ok=1
	for dir in "PHP_CodeSniffer-$PHPCS_VERSION" "WordPress-Coding-Standards-$WPCS_VERSION" "PHPCSUtils-$PHPCSUTILS_VERSION" "PHPCSExtra-$PHPCSEXTRA_VERSION"; do
		if [ -d "$TOOLS_DIR/$dir" ]; then
			printf '  present  %s\n' "$dir"
		else
			printf '  missing  %s\n' "$dir"
			ok=0
		fi
	done
	printf 'phpcs entry point: %s\n' "$(phpcs_entry)"
	printf 'installed_paths:   %s\n' "$(installed_paths)"
	return $(( ok == 1 ? 0 : 1 ))
}

if [ "$CHECK_ONLY" -eq 1 ]; then
	report
	exit $?
fi

if [ "$FORCE" -eq 1 ]; then
	rm -rf "$TOOLS_DIR"
fi
mkdir -p "$TOOLS_DIR"

if ! command -v curl >/dev/null 2>&1; then
	printf 'curl is required to download the tools.\n' >&2
	exit 2
fi
if ! command -v unzip >/dev/null 2>&1 && ! command -v python3 >/dev/null 2>&1; then
	printf 'unzip or python3 is required to unpack the tools.\n' >&2
	exit 2
fi

extract() {
	local archive="$1" target="$2"
	if command -v unzip >/dev/null 2>&1; then
		unzip -q -o "$archive" -d "$target"
	else
		python3 -c "import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])" "$archive" "$target"
	fi
}

fetch() {
	local name="$1" url="$2" expected_dir="$3"
	if [ -d "$TOOLS_DIR/$expected_dir" ]; then
		printf '  already installed  %s\n' "$expected_dir"
		return 0
	fi

	local archive="$TOOLS_DIR/$name.zip"
	local status
	status="$(curl -sL -o "$archive" -w '%{http_code}' "$url")"
	if [ "$status" != "200" ]; then
		printf '  download failed    %s (HTTP %s)\n' "$name" "$status" >&2
		rm -f "$archive"
		return 1
	fi

	printf '  downloaded         %s (%s bytes, sha256 %s)\n' \
		"$name" "$(stat -c%s "$archive")" "$(sha256sum "$archive" | cut -c1-16)"

	extract "$archive" "$TOOLS_DIR" || return 1
	rm -f "$archive"

	if [ ! -d "$TOOLS_DIR/$expected_dir" ]; then
		printf '  unexpected layout  %s (wanted %s)\n' "$name" "$expected_dir" >&2
		return 1
	fi
	return 0
}

printf 'Installing code quality tools into %s\n' "$TOOLS_DIR"
FAILED=0
fetch "phpcs-$PHPCS_VERSION" \
	"https://github.com/PHPCSStandards/PHP_CodeSniffer/archive/refs/tags/$PHPCS_VERSION.zip" \
	"PHP_CodeSniffer-$PHPCS_VERSION" || FAILED=1
fetch "wpcs-$WPCS_VERSION" \
	"https://github.com/WordPress/WordPress-Coding-Standards/archive/refs/tags/$WPCS_VERSION.zip" \
	"WordPress-Coding-Standards-$WPCS_VERSION" || FAILED=1
fetch "phpcsutils-$PHPCSUTILS_VERSION" \
	"https://github.com/PHPCSStandards/PHPCSUtils/archive/refs/tags/$PHPCSUTILS_VERSION.zip" \
	"PHPCSUtils-$PHPCSUTILS_VERSION" || FAILED=1
fetch "phpcsextra-$PHPCSEXTRA_VERSION" \
	"https://github.com/PHPCSStandards/PHPCSExtra/archive/refs/tags/$PHPCSEXTRA_VERSION.zip" \
	"PHPCSExtra-$PHPCSEXTRA_VERSION" || FAILED=1

if [ "$FAILED" -ne 0 ]; then
	printf 'One or more tools could not be installed.\n' >&2
	exit 1
fi

# Record the wiring so callers do not have to reconstruct it.
cat > "$TOOLS_DIR/phpcs-paths.env" <<ENV
# Generated by bin/setup-tools.sh. Consumed by bin/prerelease.sh.
AICFAB_PHPCS="$(phpcs_entry)"
AICFAB_PHPCBF="$(phpcbf_entry)"
AICFAB_PHPCS_INSTALLED_PATHS="$(installed_paths)"
ENV

printf '\n'
report
printf '\nRun the checks with: bin/prerelease.sh\n'
